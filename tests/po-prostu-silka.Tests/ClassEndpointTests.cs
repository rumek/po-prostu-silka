    [Fact]
    public async Task Create_refuses_a_blocked_trainer_and_an_unknown_id()
    {
        var (admin, type, _) = await ArrangeAsync();

        var blockedTrainerId = await CreateAccountAsync(
            admin, AccountStatus.Blocked, ApplicationRoles.Trainer);

        var blocked = await admin.PostAsJsonAsync(
            Endpoint, Request(type.Id, NextSlot(), blockedTrainerId));

        Assert.Equal(HttpStatusCode.BadRequest, blocked.StatusCode);

        // Not a status of its own: the selection only ever offers active trainers, so an inactive id
        // means the client is working from a stale list. Telling the caller which accounts exist but
        // are blocked would leak account state onto a scheduling surface.
        Assert.Equal(
            "unknown_instructor",
            (await blocked.Content.ReadFromJsonAsync<FailureBody>())!.Reason);

        var unknown = await admin.PostAsJsonAsync(
            Endpoint, Request(type.Id, NextSlot(), Guid.NewGuid().ToString()));

        Assert.Equal(HttpStatusCode.BadRequest, unknown.StatusCode);
        Assert.Equal(
            "unknown_instructor",
            (await unknown.Content.ReadFromJsonAsync<FailureBody>())!.Reason);
    }

    [Fact]
    public async Task The_occurrence_resolves_the_instructors_display_name()
    {
        var (admin, type, trainerId) = await ArrangeAsync();

        var created = await PostClassAsync(admin, type.Id, NextSlot(), trainerId);

        var members = await admin.GetFromJsonAsync<List<MemberBody>>("/api/admin/members");
        var expected = members!.Single(m => m.Id == trainerId).DisplayName;

        Assert.Equal(trainerId, created.InstructorUserId);
        Assert.Equal(expected, created.Instructor);
    }

    [Fact]
    public async Task Edit_can_reassign_the_instructor()
    {
        // Unlike the type, the instructor IS mutable — reassigning a class is ordinary admin work.
        var (admin, type, trainerId) = await ArrangeAsync();
        var slot = NextSlot();

        var created = await PostClassAsync(admin, type.Id, slot, trainerId);

        // A distinct display name, or the stale-name assertion below could not tell the two apart -
        // every account the fixture creates is otherwise called "Test Trainer".
        var replacement = await CreateTrainerAsync(admin, $"Zastępstwo-{Guid.NewGuid():N}");

        var response = await admin.PutAsJsonAsync(
            $"{Endpoint}/{created.Id}", Request(type.Id, slot, replacement));

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);

        var body = (await response.Content.ReadFromJsonAsync<ClassBody>())!;
        Assert.Equal(replacement, body.InstructorUserId);

        // AND the display name is the NEW trainer's, not the previous one's.
        //
        // This is the half that can regress silently. The handler builds its response from the
        // account the validation resolved, precisely because the tracked entity's Instructor
        // navigation still points at the PREVIOUS account after the id is reassigned - projecting
        // from that navigation would return a stale name with a correct id, and every other
        // assertion here would still pass.
        var members = await admin.GetFromJsonAsync<List<MemberBody>>("/api/admin/members");
        var expected = members!.Single(m => m.Id == replacement).DisplayName;

        Assert.Equal(expected, body.Instructor);
        Assert.NotEqual(created.Instructor, body.Instructor);
    }

    // --- the trainer list ------------------------------------------------------

    [Fact]
    public async Task Trainers_lists_active_trainers_only()
    {
        var admin = await AdminAsync();

        var activeTrainer = await CreateTrainerAsync(admin);
        var blockedTrainer = await CreateAccountAsync(
            admin, AccountStatus.Blocked, ApplicationRoles.Trainer);
        var plainMember = await CreateAccountAsync(
            admin, AccountStatus.Active, ApplicationRoles.User);

        var trainers = await admin.GetFromJsonAsync<List<TrainerBody>>("/api/admin/trainers");
        var ids = trainers!.Select(t => t.Id).ToHashSet();

        Assert.Contains(activeTrainer, ids);
        Assert.DoesNotContain(blockedTrainer, ids);
        Assert.DoesNotContain(plainMember, ids);
    }

    [Fact]
    public async Task Trainers_includes_an_account_holding_both_admin_and_trainer()
    {
        // prd-v2 FR-003: roles are additive, so an owner who teaches appears in the same selection as
        // everyone else. The grant goes through the real endpoint rather than the fixture, because
        // that is the path an admin actually takes.
        var admin = await AdminAsync();
        var ownerId = await CreateAccountAsync(admin, AccountStatus.Active, ApplicationRoles.Admin);

        var grant = await admin.PostAsJsonAsync(
            $"/api/admin/members/{ownerId}/roles/trainer", new { });

        Assert.Equal(HttpStatusCode.OK, grant.StatusCode);

        var trainers = await admin.GetFromJsonAsync<List<TrainerBody>>("/api/admin/trainers");

        Assert.Contains(ownerId, trainers!.Select(t => t.Id));
    }

